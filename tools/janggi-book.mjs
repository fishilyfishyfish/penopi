// Builds janggi/book.js: the engine's own opening book (no published janggi theory was at hand).
//   node tools/janggi-book.mjs [plies = 4] [ms = 6000] [threads = 4] [margin = 40]
// For each of the 16 상차림 pairs, breadth first from the start: each position is searched for `ms`, then twice more
// with the moves found so far excluded (ms/2 each); moves within `margin` of the best (up to 3) go into the book,
// and their positions are expanded until `plies` moves have been played. The file maps a position (FEN without the
// move counters) to its book moves (engine notation, e.g. "i4h4"). tools/janggi-book-check.mjs scores it afterwards.
import { Worker, isMainThread, parentPort, workerData } from 'worker_threads';
import { createRequire } from 'module';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';

const here = fileURLToPath(import.meta.url), root = path.resolve(path.dirname(here), '..');
const { JanggiEngine } = createRequire(import.meta.url)(path.join(root, 'janggi', 'engine.js'));
const key = (fen) => fen.split(' ').slice(0, 2).join(' ');
if (isMainThread) {
  const [pliesArg, msArg, threadsArg, marginArg] = process.argv.slice(2);
  const PLIES = Number(pliesArg || 4), MS = Number(msArg || 6000), THREADS = Number(threadsArg || 4), MARGIN = Number(marginArg || 40);
  const book = new Map(), t0 = Date.now();
  let level = [];
  for (let a = 0; a < 4; a++) for (let b = 0; b < 4; b++) level.push({ arr: [a, b], moves: [] });
  for (let ply = 0; ply < PLIES; ply++) {
    const R = JanggiEngine({ ttBits: 4 });
    // the same position reached twice (another move order) is searched once
    const todo = [], seen = new Set();
    for (const job of level) {
      R.setup(...job.arr); for (const m of job.moves) R.play(m);
      const k = key(R.fen());
      if (book.has(k) || seen.has(k)) continue;
      seen.add(k); todo.push({ ...job, k });
    }
    const results = await new Promise((resolve) => {
      const out = [];
      let next = 0, live = 0;
      const start = () => {
        if (next >= todo.length) { if (!live) resolve(out); return; }
        const job = todo[next++]; live++;
        const wk = new Worker(here, { workerData: { job, MS, MARGIN } });
        wk.on('message', (r) => out.push(r));
        wk.on('exit', () => { live--; start(); });
      };
      for (let t = 0; t < THREADS; t++) start();
    });
    const nextLevel = [];
    for (const r of results) {
      book.set(r.k, r.moves.map((x) => x.uci));
      for (const x of r.moves) nextLevel.push({ arr: r.arr, moves: r.path.concat(x.m) });
    }
    level = nextLevel;
    console.log(`ply ${ply + 1}: ${results.length} positions searched, book ${book.size} positions, ${((Date.now() - t0) / 60000).toFixed(1)} min`);
  }
  const entries = [...book.entries()].sort((x, y) => (x[0] < y[0] ? -1 : 1));
  const body = entries.map(([k, ms]) => `  '${k}': ${JSON.stringify(ms)},`).join('\n');
  fs.writeFileSync(path.join(root, 'janggi', 'book.js'), `// Janggi opening book, generated by tools/janggi-book.mjs (the engine's own deep searches; ${new Date().toISOString().slice(0, 10)}).
// Position (FEN board and side to move) → book moves in engine notation (from-to, e.g. "i4h4"). Penopi plays one of them at random.
export const BOOK = {
${body}
};
`);
  console.log(`wrote janggi/book.js: ${book.size} positions`);
} else {
  const { job, MS, MARGIN } = workerData;
  const E = JanggiEngine({ ttBits: 20 });
  E.setup(...job.arr); for (const m of job.moves) E.play(m);
  const found = [];
  const first = E.think({ time: MS, soft: 1 });
  found.push({ m: first.move, s: first.score });
  for (let k = 0; k < 2; k++) {
    E.setup(...job.arr); for (const m of job.moves) E.play(m);
    const info = E.think({ time: MS / 2, soft: 1, exclude: found.map((x) => x.m) });
    if (!info.move || info.score < first.score - MARGIN) break;
    found.push({ m: info.move, s: info.score });
  }
  // notation in the position itself
  E.setup(...job.arr); for (const m of job.moves) E.play(m);
  parentPort.postMessage({ k: job.k, arr: job.arr, path: job.moves, moves: found.filter((x) => x.m !== E.PASS).map((x) => ({ m: x.m, uci: E.uci(x.m), s: x.s })) });
}
